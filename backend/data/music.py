def get_songs_for_emotion(emotion, count=3):
    import random
    emotion = emotion.lower().strip()
    songs = EMOTION_SONGS.get(emotion, EMOTION_SONGS["neutral"])
    random.shuffle(songs)
    return songs[:count]

def format_songs_for_ai(emotion, songs):
    text = f"Based on your **{emotion}** mood, here are my top picks:\n\n"
    for i, s in enumerate(songs, 1):
        text += f"**{i}. {s['title']}** - {s['artist']} ({s['genre']})\n"
    return text
